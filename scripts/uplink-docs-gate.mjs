#!/usr/bin/env node
/**
 * Every client-bearing Uplink has a GENERATED page. Absence is a failure, never
 * an N/A.
 *
 * ## Why this is central and not a per-package opt-in
 *
 * `gonogo-uplink docs` needs no `package.json` script, and the drift gate that
 * goes with it (`docs --check`) was reached through one: a `docs:check` line an
 * Uplink either had or did not. Exactly one of ten had it. A gate you opt into is
 * a gate that describes whoever remembered, and the nine Uplinks with no page at
 * all reported as a clean matrix because nothing asked them for one.
 *
 * So the question is asked HERE, over the discovered set, and an Uplink with a
 * client is expected to have a page, and a test that gates it. That splits the
 * work three ways:
 *
 *   • THIS script asks whether a page EXISTS, is generated, and is GATED by a
 *     test in the Uplink's own suite. Pure filesystem, runs in a second, in
 *     `ci.yml` and the pre-push hook.
 *   • that per-Uplink test (`expectUplinkPageCurrent`) asks whether the PROSE is
 *     current, on every local run of the Uplink's suite. It has to live in the
 *     Uplink's own process rather than in one repo-wide walk here: the
 *     registries are global, so a second client loaded beside the first is read
 *     as a host of it and both pages come out wrong.
 *   • `gonogo-uplink docs --check`, per leg in `uplink.yml`, asks whether the
 *     IMAGES are current too. That renders every widget in chromium and is far
 *     too slow to run for every Uplink on every push.
 *
 * None substitutes for another: a page can be missing (this catches it),
 * describing last month's registrations (the per-Uplink test catches it), or
 * carrying a picture of a widget that has since been restyled (only the browser
 * half catches that).
 *
 * The test half was added 2026-09-16, when moving `EXTENSION_API_VERSION` to
 * 2.0.0 left six of seven "Built against" lines stale and only kOS, the one
 * Uplink that happened to have the test, said so before the push.
 *
 * ## A shrink-only ratchet, and it is already empty
 *
 * `NO_PAGE_DEBT` exists because seeding a gate red for nine of ten would be a
 * second permanently-failing job, and this repo owns one already and has twice
 * had a real failure hide behind it. It was seeded and emptied on the same day,
 * so every client-bearing Uplink is held to having a page and a new one is
 * documented from the day it lands.
 *
 * Both directions. An Uplink that gains a page and stays listed fails as STALE,
 * because a debt list nobody prunes stops describing anything.
 *
 * Usage:
 *   uplink-docs-gate.mjs            fail on an unexcused missing page, or a stale excuse
 *   uplink-docs-gate.mjs --report   print the state and exit 0
 */

import { execFileSync } from "node:child_process";
import {
  existsSync,
  mkdirSync,
  mkdtempSync,
  readdirSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const report = process.argv.includes("--report");

/**
 * Uplinks with no generated page. SHRINK ONLY, and it is EMPTY.
 *
 * It was seeded 2026-08-28 at nine of ten client-bearing Uplinks, and emptied
 * the same day: one had a full generated page, `GonogoKerbcastUplink` had a
 * HAND-WRITTEN README (which is worse than none for this gate's purpose, since it
 * looks documented while describing registrations nothing checks), and the other
 * eight had nothing.
 *
 * The list stays here rather than being deleted with its last entry, because
 * empty is the STATEMENT: a new Uplink is held to having a page from the day it
 * lands, and there is no grandfathering left to inherit. An entry added back
 * needs a reason in a comment beside it.
 */
const NO_PAGE_DEBT = new Set([]);

/**
 * The banner `buildReadme` writes as the page's first line.
 *
 * Matched because the alternative is asking only whether README.md exists, and a
 * hand-written README passes that. A page nobody generated is the failure this
 * gate is for, and it is indistinguishable from a generated one by presence
 * alone.
 */
const GENERATED_BANNER = "<!-- Generated by `gonogo-uplink docs`";

/**
 * The call that makes a test file the page's gate.
 *
 * Matched by the call rather than by a filename, because the filename is a
 * convention and the call is the check. A file named `uplink-page.test.ts` that
 * asserts something else would pass a name match while gating nothing.
 */
const PAGE_CHECK_CALL = "expectUplinkPageCurrent(";

/** Every `*.test.ts(x)` under `dir`, node_modules and dist aside. */
function testFiles(dir) {
  const found = [];
  const walk = (at) => {
    let entries;
    try {
      entries = readdirSync(at, { withFileTypes: true });
    } catch {
      return;
    }
    for (const entry of entries) {
      if (entry.name === "node_modules" || entry.name === "dist") continue;
      const full = join(at, entry.name);
      if (entry.isDirectory()) walk(full);
      else if (/\.test\.tsx?$/.test(entry.name)) found.push(full);
    }
  };
  walk(dir);
  return found;
}

/**
 * What one Uplink's client directory is missing, as a list of reasons. Empty
 * means it has a page and a test holding the page to the code.
 *
 * A pure function of a directory, so the self-check below can run it against a
 * planted tree. A predicate that can only be run against the real repo cannot be
 * shown to fail, and a check that cannot fail reports success.
 */
export function missingPageReasons(clientDir) {
  const reasons = [];
  if (
    !testFiles(clientDir).some((file) =>
      readFileSync(file, "utf8").includes(PAGE_CHECK_CALL),
    )
  ) {
    reasons.push("no test calls expectUplinkPageCurrent()");
  }
  const readme = join(clientDir, "README.md");
  if (!existsSync(readme)) {
    reasons.push("no README.md");
  } else if (!readFileSync(readme, "utf8").startsWith(GENERATED_BANNER)) {
    reasons.push("README.md was not generated (no generator banner on line 1)");
  }

  if (!existsSync(join(clientDir, "gonogo-uplink.json"))) {
    reasons.push("no gonogo-uplink.json");
  }
  // Deliberately NOT a check for a prose file. There was one (`uplink.md`), and
  // it is gone: a markdown file beside the client is an invitation to write
  // markdown, and the ten in this repo grew install notes, per-widget rationale
  // and restatements of rules true of every Uplink. What the page needs from an
  // author is one field, `description` on `defineUplinkClient`, and the generator
  // refuses a page without it, so its absence is caught by the drift check
  // failing rather than by a filesystem test here.
  return reasons;
}

/**
 * Prove the predicate can see a missing page before trusting it about the real
 * ones.
 *
 * Five planted trees, because the ways a page goes missing are not the same
 * shape and a predicate that catches one is not a predicate that catches all:
 * nothing there at all, a hand-written README, a complete page with no test
 * gating it, a page whose only test asserts something else, and a complete page
 * (which must come back clean, or the gate is failing everything and the pass
 * means nothing).
 */
function selfCheck() {
  const dir = mkdtempSync(join(tmpdir(), "uplink-docs-gate-"));
  try {
    const tree = (name, files) => {
      const at = join(dir, name);
      mkdirSync(at, { recursive: true });
      for (const [file, body] of Object.entries(files)) {
        const full = join(at, file);
        mkdirSync(dirname(full), { recursive: true });
        writeFileSync(full, body);
      }
      return at;
    };
    const page = {
      "README.md": `${GENERATED_BANNER} -->\n\n# Some Uplink\n`,
      "gonogo-uplink.json": "{}\n",
    };
    const gate = { "src/uplink-page.test.ts": "expectUplinkPageCurrent();\n" };

    const bare = missingPageReasons(tree("bare", {}));
    const handWritten = missingPageReasons(
      tree("hand-written", {
        ...gate,
        "README.md": "# Some Uplink\n\nWritten by a person.\n",
        "gonogo-uplink.json": "{}\n",
      }),
    );
    const ungated = missingPageReasons(tree("ungated", page));
    const otherTest = missingPageReasons(
      tree("other-test", {
        ...page,
        "src/widget.test.tsx": "it('renders', () => {});\n",
      }),
    );
    const generated = missingPageReasons(
      tree("generated", { ...page, ...gate }),
    );

    const faults = [];
    if (bare.length !== 3) {
      faults.push(
        `an empty client directory should be missing all three things, and this reported ${bare.length}`,
      );
    }
    if (!handWritten.some((r) => r.includes("not generated"))) {
      faults.push(
        "a hand-written README passed, so this gate cannot tell a generated page from a typed one",
      );
    }
    for (const [label, reasons] of [
      ["a page with no test at all", ungated],
      ["a page whose only test asserts something else", otherTest],
    ]) {
      if (!reasons.some((r) => r.includes("expectUplinkPageCurrent"))) {
        faults.push(
          `${label} passed, so this gate cannot see an ungated page and every stale one reads as current`,
        );
      }
    }
    if (generated.length !== 0) {
      faults.push(
        `a complete generated page was reported as missing: ${generated.join("; ")}`,
      );
    }
    if (faults.length > 0) {
      console.error(
        "✖ uplink-docs-gate cannot see its own failure, so its verdict about the real\n" +
          "  Uplinks means nothing:\n" +
          faults.map((f) => `    ${f}`).join("\n"),
      );
      process.exit(1);
    }
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
}

selfCheck();

/**
 * Discovered from the same matrix CI iterates, never a list here. A hand-kept
 * list of which Uplinks have a client is the shape this repo has deleted five
 * times, and the failure mode is the one that matters: an Uplink missing from the
 * list is an Uplink this never checks, reported as a clean pass.
 */
const withClient = JSON.parse(
  execFileSync("node", [join(ROOT, "scripts/uplink-matrix.mjs")], {
    encoding: "utf8",
  }),
).filter((leg) => leg.client);

if (withClient.length === 0) {
  console.error(
    "✖ the matrix reported no Uplink with a client, so this examined nothing and would have\n" +
      "  exited clean. Discovery is broken rather than the repo being empty; a docs gate that\n" +
      "  inspects zero pages is worse than no gate.",
  );
  process.exit(1);
}

const rows = withClient.map((leg) => ({
  id: leg.id,
  pkg: leg.pkg,
  reasons: missingPageReasons(join(ROOT, "mod", leg.id, "client")),
}));

/** True when the only thing an Uplink lacks is the test that gates its page. */
const onlyUngated = (row) =>
  row.reasons.length > 0 &&
  row.reasons.every((reason) => reason.includes("expectUplinkPageCurrent"));

for (const row of rows) {
  const state =
    row.reasons.length === 0
      ? "page"
      : onlyUngated(row)
        ? "UNGATED"
        : "NO PAGE";
  console.log(
    `  ${state.padEnd(8)} ${row.id.padEnd(38)} ${row.reasons.join("; ")}`,
  );
}

const without = rows.filter((row) => row.reasons.length > 0);
const unexcused = without.filter((row) => !NO_PAGE_DEBT.has(row.id));
const stale = rows.filter(
  (row) => row.reasons.length === 0 && NO_PAGE_DEBT.has(row.id),
);

if (report) {
  console.log(
    `\n${rows.length - without.length} of ${rows.length} client-bearing Uplink(s) have a generated ` +
      `page. ${without.length} in NO_PAGE_DEBT.`,
  );
  process.exit(0);
}

if (stale.length > 0) {
  console.error(
    `\n✖ ${stale.length} Uplink(s) now have a generated page and are still in NO_PAGE_DEBT:\n` +
      stale.map((row) => `    ${row.id}`).join("\n") +
      "\n\n  Delete those entries from scripts/uplink-docs-gate.mjs to ratchet the gate down.",
  );
  process.exit(1);
}

if (unexcused.length > 0) {
  const ungated = unexcused.filter(onlyUngated);
  const pageless = unexcused.filter((row) => !onlyUngated(row));
  const parts = [
    `\n✖ ${unexcused.length} client-bearing Uplink(s) fail the page gate:\n` +
      unexcused
        .map((row) => `    ${row.id}: ${row.reasons.join("; ")}`)
        .join("\n"),
  ];
  if (pageless.length > 0) {
    parts.push(
      "\n  An Uplink's page is generated from its registrations, its contract slice and its\n" +
        "  renders, so the only part to write is the prose. Create client/uplink.md with a lede\n" +
        "  (what it is for, which mod it integrates, install notes) and optional\n" +
        "  `## widget:<id>` sections, then:\n" +
        pageless
          .map(
            (row) => `    pnpm --filter '${row.pkg}' exec gonogo-uplink docs`,
          )
          .join("\n"),
    );
  }
  if (ungated.length > 0) {
    const template = rows.find((row) => row.reasons.length === 0);
    parts.push(
      "\n  These have a page that nothing holds to the code, so a stale one passes every\n" +
        "  local gate. Copy the five-line test every other Uplink carries:\n" +
        ungated
          .map((row) =>
            template
              ? `    cp mod/${template.id}/client/src/uplink-page.test.ts mod/${row.id}/client/src/`
              : `    add mod/${row.id}/client/src/uplink-page.test.ts calling expectUplinkPageCurrent`,
          )
          .join("\n"),
    );
  }
  console.error(parts.join("\n"));
  process.exit(1);
}

console.log(
  `\nall ${rows.length} client-bearing Uplink(s) have a generated page` +
    `${without.length > 0 ? `; ${without.length} in NO_PAGE_DEBT, none outside it` : ""}.`,
);
