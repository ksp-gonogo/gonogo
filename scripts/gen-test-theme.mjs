/**
 * Generates `mod/sitrep-sdk/src/__generated__/test-theme.ts`.
 *
 * `@ksp-gonogo/sitrep-sdk/testing`'s `render` mounts a theme, because every
 * ui-kit primitive reads `theme.space[...]` straight off the styled-components
 * context and a render with no provider is a TypeError rather than a fallback.
 * The theme is a MODEL fact owned by `@ksp-gonogo/theme`, so this copies it
 * across.
 *
 * Generated rather than imported because the sdk is the leaf every other package
 * depends on: it can name neither `@ksp-gonogo/theme` (`private: true`, so a
 * consumer cannot install it) nor `@ksp-gonogo/ui-kit` (which imports the sdk in
 * 19 files, so the edge would be a cycle). Same shape as `gen-unit-kinds.mjs`,
 * for the same reason: two packages that cannot import each other, one owns the
 * fact.
 *
 * ## Not an accessor, and not a lazy import
 *
 * A runtime `await import("@ksp-gonogo/theme")` from the sdk looks like it dodges
 * the build graph. It resolves in this workspace only because pnpm hoists the
 * package, and a third-party author installing `@ksp-gonogo/sitrep-sdk` from the
 * registry gets a module-not-found. That is the same mechanism as an Uplink
 * importing a package its manifest never declares, which is the defect this whole
 * effort exists to remove. A dependency direction cannot be fixed by deferring
 * when it is resolved, only hidden until someone outside the monorepo builds.
 *
 * ## Not derived from the property path either
 *
 * The first design emitted `var(--...)` by kebab-casing the property path and
 * singularising the group. 18 of the 45 leaves do not follow it: `space.md` is
 * `--space-8` (the t-shirt names are the published `ThemeSpace` contract and are
 * deliberately not renamed to match the rung numbers), `typography.size.xs` is
 * `--font-size-xs`, `typography.weight.regular` is the number `400`, and
 * `borders.subtle` is `"1px solid var(...)"`. An arbitrary mapping is not
 * recoverable from a naming rule, so the values are copied verbatim.
 *
 * Reads the real values by importing the module rather than parsing it, same as
 * the unit-kinds generator, whose header records that a regex over the source was
 * the first attempt and silently matched nothing.
 *
 * Kept current by `packages/core/src/sdk-testing-theme.conformance.test.ts`,
 * which walks the real theme in both directions. A generator nobody runs is its
 * own silent failure; that test is what makes it loud.
 */
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = join(root, "mod/sitrep-sdk/src/__generated__/test-theme.ts");

const { defaultDarkTheme } = await import(
  join(root, "packages/theme/src/defaultDarkTheme.ts")
);

let leaves = 0;
function emit(node, depth) {
  const pad = "  ".repeat(depth);
  const out = [];
  for (const [key, value] of Object.entries(node)) {
    const k = /^[A-Za-z_][A-Za-z0-9_]*$/.test(key) ? key : JSON.stringify(key);
    if (value !== null && typeof value === "object") {
      out.push(`${pad}${k}: {`, ...emit(value, depth + 1), `${pad}},`);
    } else {
      leaves++;
      out.push(`${pad}${k}: ${JSON.stringify(value)},`);
    }
  }
  return out;
}

const body = emit(defaultDarkTheme, 1);

const lines = [
  "//     This code was generated by scripts/gen-test-theme.mjs.",
  "//     Changes to this file may cause incorrect behavior and will be lost if",
  "//     the code is regenerated.",
  "//",
  "// The theme `@ksp-gonogo/sitrep-sdk/testing`'s `render` mounts. A copy of",
  "// `@ksp-gonogo/theme`'s `defaultDarkTheme`, which owns it.",
  "//",
  "// Copied rather than imported because the sdk is the leaf: it can name neither",
  "// `@ksp-gonogo/theme` (private, so a consumer cannot install it) nor",
  "// `@ksp-gonogo/ui-kit` (imports the sdk, so the edge would cycle). See the",
  "// generator's header for why an accessor or a path-derived Proxy does not work.",
  "//",
  "// Every value here is a `var(--...)` handle or a literal; the numbers behind them",
  "// live in `tokens.css`, which no test loads. So a test asserts on",
  "// `padding: var(--space-8)`, exactly as the app renders it.",
  "",
  "export const GENERATED_TEST_THEME = {",
  ...body,
  "} as const;",
  "",
];

writeFileSync(OUT, lines.join("\n"));
console.log(
  `codegen (test-theme) -> ${OUT} (${leaves} leaves, ` +
    `${Object.keys(defaultDarkTheme).length} groups)`,
);
