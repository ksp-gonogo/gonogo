/**
 * Generates `packages/ui-kit/src/__generated__/unit-kinds.ts`.
 *
 * ui-kit used to hand-maintain its own symbol -> kind table beside the SDK's,
 * and the two drifted: seven units disagreed on what their kind was CALLED
 * (`kW` was `energyRate` in one and `power` in the other). Nothing caught it,
 * because the gate that existed asked whether every token had SOME kind rather
 * than whether the two agreed on which.
 *
 * A kind is a MODEL fact, so the SDK owns it and this copies it across. It is
 * generated rather than imported because `packages/ui-kit` ships with no
 * runtime dependencies at all: every `sitrep-sdk` import in that package is
 * type-only and says so. A generated data file keeps that property.
 *
 * Reads the SDK's real values by importing the module, rather than parsing it.
 * A regex over the source was the first attempt at the guard this replaces, and
 * it silently matched nothing.
 */
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = join(root, "packages/ui-kit/src/__generated__/unit-kinds.ts");

const { UNIT_DEFINITIONS } = await import(
  join(root, "mod/sitrep-sdk/src/unit-system/definitions.ts")
);
const { KNOWN_SITREP_UNITS } = await import(
  join(root, "scripts/known-sitrep-units.mjs")
);

/** symbol -> { kind, ratio }, from the model. */
const kinds = {};
for (const [symbol, def] of Object.entries(UNIT_DEFINITIONS)) {
  kinds[symbol] = { kind: def.kind, ratio: def.ratio };
}

// A token the CONTRACT declares but the model has no unit for is a
// non-quantity: `text`, `flag`, `enum`, `id`, `n/a`. They have no dimension, so
// they cannot be units, but a formatter still has to know what they are. Their
// kind is the token itself, which is one fewer invented name to keep in sync.
const nonQuantity = KNOWN_SITREP_UNITS.filter((token) => !(token in kinds));
for (const token of nonQuantity) {
  kinds[token] = { kind: token, ratio: 1 };
}

const lines = [
  "//     This code was generated by scripts/gen-unit-kinds.mjs.",
  "//     Changes to this file may cause incorrect behavior and will be lost if",
  "//     the code is regenerated.",
  "//",
  "// A unit's KIND is a model fact, owned by mod/sitrep-sdk's UNIT_DEFINITIONS.",
  "// ui-kit reads it from here rather than keeping its own copy, because the two",
  "// copies drifted: seven units disagreed on what their kind was called.",
  "//",
  "// Generated rather than imported so that packages/ui-kit keeps its zero",
  "// runtime dependencies. A token the contract declares but the model has no",
  "// unit for is a non-quantity, and its kind is the token itself.",
  "//",
  "// The ratio converts to the kind's BASE unit, which is what lets the format",
  "// prop re-express a value in any unit of the same kind without ui-kit",
  "// keeping conversion factors of its own.",
  "",
  "// `as const` is load-bearing. The format prop's accepted values are a mapped",
  "// type over this object, so widening it to Record<string, ...> would silently",
  "// turn that validation off while leaving the runtime behaviour in place. This",
  "// is the third table in this system to need saying so.",
  "export const GENERATED_UNIT_KINDS = {",
  ...Object.keys(kinds)
    .sort()
    .map(
      (symbol) =>
        `  ${JSON.stringify(symbol)}: { kind: ${JSON.stringify(kinds[symbol].kind)}, ratio: ${kinds[symbol].ratio} },`,
    ),
  "} as const;",
  "",
];

writeFileSync(OUT, lines.join("\n"));
console.log(
  `codegen (unit-kinds) -> ${OUT} (${Object.keys(kinds).length} symbols, ` +
    `${nonQuantity.length} non-quantity)`,
);
