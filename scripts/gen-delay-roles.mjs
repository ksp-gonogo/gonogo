/**
 * Generates `mod/sitrep-sdk/src/__generated__/delay-roles.ts`.
 *
 * A channel's `DelayRole` decides whether its value may be read as of TRUE NOW
 * or only as of `now - light-time`. It has been declared per channel on the mod
 * since the delay architecture landed, and until this file existed no client
 * code could see it: every topic was read at the delayed view time, so a
 * `TrueNow` frame stamped at the true UT sat unreadable for exactly the
 * light-time the reveal gate had just been told to skip.
 *
 * Same chain as the reckonability marks (`RtConfig.EmitReckonability` ->
 * `__generated__/reckonability.ts` -> `../reckonability.ts` -> a key union the
 * type layer branches on), with one difference forced by where the fact lives:
 * a reckonability mark is an attribute in `Sitrep.Contract`, which the codegen
 * reflects over, and a channel's delay role is a property of the
 * `ChannelDeclaration` inside the PLUGIN assembly, which it cannot. So the
 * extraction is the same C# source scan `asyncapi.yaml` already publishes this
 * fact from (`scripts/asyncapi/sources.mjs`), and the two artifacts cannot
 * disagree because there is one scan.
 */
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import { readChannelDispositions } from "./asyncapi/sources.mjs";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = join(root, "mod/sitrep-sdk/src/__generated__/delay-roles.ts");

/**
 * A floor, not an equality. The count moves whenever a channel is reclassified
 * and that is ordinary, but a scan that matches NOTHING compares equal to
 * itself, writes an empty table and reports success, and an empty table here
 * reads as "every channel is delayed", which is exactly the state this file
 * exists to end.
 */
const FLOOR = 20;

const dispositions = readChannelDispositions(root);
const trueNow = [...dispositions.entries()]
  .filter(([, disposition]) => disposition.delay === "true-now")
  .map(([topic]) => topic)
  .sort();

if (trueNow.length < FLOOR) {
  console.error(
    `✖ delay-roles: the scan found ${trueNow.length} TrueNow channels, fewer ` +
      `than the ${FLOOR} this repo has ever had. That is the scan being broken ` +
      "rather than the mod delaying everything. Refusing to write the table.",
  );
  process.exit(1);
}

const lines = [
  "//     This code was generated by scripts/gen-delay-roles.mjs.",
  "//     Changes to this file may cause incorrect behavior and will be lost if",
  "//     the code is regenerated.",
  "//",
  "// Derived by scanning every ChannelDeclaration in the plugin assemblies for",
  "// its declared DelayRole: the same scan asyncapi.yaml publishes",
  "// `x-sitrep-delay-role` from. A topic ABSENT here is DELAYED, which is the",
  "// contract's own default and the safe answer: a delayed read of a ground-side",
  "// fact is merely late, where a true-now read of a craft's state would show an",
  "// operator the future.",
  "//",
  "// DYNAMIC topics cannot appear here. A per-vessel or per-part namespace is",
  "// registered at runtime and has no declaration for the scan to find, so it is",
  "// absent and therefore delayed, which is the right answer for every one of",
  "// them that exists today (they all describe a craft). See ../delay-roles.ts.",
  "",
  "/** Every channel the mod declares `DelayRole.TrueNow`. */",
  "export const GENERATED_TRUENOW_TOPICS = [",
  ...trueNow.map((topic) => `  ${JSON.stringify(topic)},`),
  "] as const;",
  "",
  "/** One of the topics above, as a key union for the type layer. */",
  "export type GeneratedTrueNowTopic =",
  "  (typeof GENERATED_TRUENOW_TOPICS)[number];",
  "",
];

writeFileSync(OUT, lines.join("\n"));
console.log(`codegen (delay-roles) -> ${OUT} (${trueNow.length} TrueNow)`);
