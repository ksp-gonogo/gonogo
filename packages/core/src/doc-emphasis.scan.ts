import { execFileSync } from "node:child_process";
import { readFileSync } from "node:fs";
import { join } from "node:path";

/**
 * The scan behind `styleguide-doc-emphasis.test.ts`.
 *
 * The rule: no capitals for emphasis. A word in capitals is an
 * acronym or a label the UI prints; if a sentence needs the stress to be read
 * correctly, the sentence is reworded. Emphasis capitals do not land with a
 * reader, so the rule covers every doc comment in the repo (`/** *\/` in TS and
 * TSX, `///` in C#) and not only the published ones. A plain `//` comment is
 * outside it.
 *
 * What counts as A hit: a run of two or more capital letters, standing alone as
 * a word in prose, that is not in {@link ACRONYMS}. Three kinds of text are
 * masked out first, because a capital word there is the thing itself and not
 * stress: a code span or fence, a quoted string (a label the UI prints), and
 * markup (`{@link}`, XML tags, `@example` bodies). A token containing a digit
 * (`AG1`, `M2`, `TS2367`) is a name or a code and passes.
 *
 * The acronym list is built from what the tree really writes. It is a list of
 * names (KSP, UT, SOI), units (MB) and file or protocol names (JSON, HTTP). A
 * new entry means the word is a name in the game's or the stack's vocabulary,
 * never a word that was being shouted.
 */

/** Acronyms, units and file or protocol names the tree writes in capitals. */
export const ACRONYMS: ReadonlySet<string> = new Set(
  `AA ABI AGL AGX AIAA API APG ARIA ASCII ASL AST AU BCL CC CCSDS CDP CI CJS CKAN
   CLI CLR CPU CRUD CSF CSS DFS DLC DLL DN DOM DSN DTLS EC ERE ESM ETA EVA FAB
   FIFO FSM GB GC GIF GM GOP GPU GUID HMR HTML HTTP HTTPS HUD ICE ID IDS IIFE IL
   IO IP ISP ISRU JIT JS JSON JSX KAC KB KSC KSP LAN LKO MB MIME MPL MSW MVID NET
   NRE OEM OS PAW PBDS PCDS PCM PID PNG POCO POSIX PQS PR PTT QR RA RCS README
   RFC RGB RGBA RGL RMS RNG RO RPC RSS RTL RTP SABR SAS SCET SDK SI SMA SOI SPA
   SPH SPI SSE SSH SSR STUN SVG TCP TLS TSX TS TTL TWR UA UDP UI URI URL USB UT
   UTC UUID UX VAB VID W3C WAV WCAG WS XML YAML COE2RV JONSWAP RAAN ACK AG APM
   BFS CCW CLAUDE CME COLS CONS CORS DDNS DEP ENOENT ENOSPC FBW GH GNC HDG HH II
   FAR KK LCD LM LOS LTR MAINMENU MM MVP NOGO OWLT PC PCH POI PROD RC RLL RPM RT RTG
   SC SPACECENTER SS TODO TRACKSTATION ULP XYZ CSPRNG`
    .split(/\s+/)
    .filter(Boolean),
);

/** Generated by path. Codegen output is not anyone's prose to fix. */
const GENERATED_PATH_RE =
  /(?:\.d\.ts$|\.(?:g|generated)\.[a-z]+$|\/(?:generated|__generated__|dist|vendor|node_modules|obj|bin)\/)/;

const GENERATED_HEADER_RE = /<auto-?generated|@generated/i;

const SOURCE_RE = /\.(ts|tsx|mts|cs)$/;

export interface EmphasisHit {
  /** 1-indexed line of the word. */
  line: number;
  /** Offset of the word in the file. */
  offset: number;
  word: string;
  /** The trimmed line, for a failure message. */
  text: string;
}

/** Same-length copy of `s` with the span at `[from, to)` blanked, newlines kept. */
function blank(chars: string[], from: number, to: number): void {
  for (let i = from; i < to; i++) {
    if (chars[i] !== "\n") chars[i] = " ";
  }
}

function maskWith(chars: string[], text: string, re: RegExp): void {
  for (const m of text.matchAll(re)) {
    blank(chars, m.index ?? 0, (m.index ?? 0) + m[0].length);
  }
}

/**
 * The comment body with everything that is not prose blanked out, the same
 * length as the input so a match offset is also an offset into the raw source.
 */
export function proseMask(body: string): string {
  const chars = [...body];
  const masks: RegExp[] = [
    /```[\s\S]*?```/g,
    /`[^`]*`/g,
    /@example[\s\S]*?(?=\n\s*\*?\s*@[a-z]|$)/g,
    /<(c|code)>[\s\S]*?<\/\1>/g,
    /<[^>\n]*>/g,
    /\{@[^}]*\}/g,
    /\$\{[^}]*\}/g,
    /https?:\/\/\S+/g,
    /"[^"]{1,80}"/g,
    /“[^”]{1,80}”/g,
    /(?<![\w])'[^'\n]{1,40}'(?!\w)/g,
  ];
  for (const re of masks) maskWith(chars, body, re);
  return chars.join("");
}

interface DocBlock {
  /** Offset of the body in the file. */
  start: number;
  body: string;
}

/** Every doc comment body in a source file, at its file offset. */
export function docBlocks(source: string, csharp: boolean): DocBlock[] {
  const blocks: DocBlock[] = [];
  if (csharp) {
    const re = /^[ \t]*\/\/\/.*(?:\n[ \t]*\/\/\/.*)*/gm;
    for (const m of source.matchAll(re)) {
      blocks.push({ start: m.index ?? 0, body: m[0] });
    }
    return blocks;
  }
  const re = /\/\*\*(?!\/)[\s\S]*?\*\//g;
  for (const m of source.matchAll(re)) {
    blocks.push({ start: m.index ?? 0, body: m[0] });
  }
  return blocks;
}

export const WORD_RE = /(?<![\w\-./'])[A-Z][A-Z0-9]+(?![\w\-/])/g;

/** Every emphasis word in one file's doc comments, in file order. */
export function emphasisIn(source: string, csharp: boolean): EmphasisHit[] {
  const hits: EmphasisHit[] = [];
  const lineStarts: number[] = [0];
  for (let i = 0; i < source.length; i++) {
    if (source[i] === "\n") lineStarts.push(i + 1);
  }
  const lineOf = (offset: number): number => {
    let lo = 0;
    let hi = lineStarts.length - 1;
    while (lo < hi) {
      const mid = (lo + hi + 1) >> 1;
      if (lineStarts[mid] <= offset) lo = mid;
      else hi = mid - 1;
    }
    return lo;
  };
  for (const block of docBlocks(source, csharp)) {
    const masked = proseMask(block.body);
    for (const m of masked.matchAll(WORD_RE)) {
      const word = m[0];
      if (/\d/.test(word) || ACRONYMS.has(word)) continue;
      const offset = block.start + (m.index ?? 0);
      const line = lineOf(offset);
      hits.push({
        line: line + 1,
        offset,
        word,
        text: source
          .slice(lineStarts[line], lineStarts[line + 1] ?? source.length)
          .trim(),
      });
    }
  }
  return hits;
}

export interface EmphasisScan {
  /** Files listed by git, before generated ones are dropped. */
  enumerated: number;
  /** Files whose doc comments were read. */
  scanned: number;
  hits: Map<string, EmphasisHit[]>;
}

function repoRoot(): string {
  return execFileSync("git", ["rev-parse", "--show-toplevel"], {
    encoding: "utf8",
  }).trim();
}

/** Every hand-written TS, TSX and C# file, including ones not yet tracked. */
export function sourceFiles(root: string): string[] {
  const out = execFileSync(
    "git",
    ["ls-files", "--cached", "--others", "--exclude-standard", "-z"],
    { cwd: root, encoding: "utf8", maxBuffer: 256 * 1024 * 1024 },
  );
  return out.split("\0").filter(Boolean);
}

export function scanDocEmphasis(
  covers: (rel: string) => boolean = () => true,
): EmphasisScan {
  const root = repoRoot();
  const listed = sourceFiles(root).filter((f) => SOURCE_RE.test(f));
  const hits = new Map<string, EmphasisHit[]>();
  let scanned = 0;
  for (const file of listed) {
    if (GENERATED_PATH_RE.test(`/${file}`) || !covers(file)) continue;
    let source: string;
    try {
      source = readFileSync(join(root, file), "utf8");
    } catch {
      continue;
    }
    if (GENERATED_HEADER_RE.test(source.slice(0, 400))) continue;
    scanned++;
    const found = emphasisIn(source, file.endsWith(".cs"));
    if (found.length > 0) hits.set(file, found);
  }
  return { enumerated: listed.length, scanned, hits };
}
