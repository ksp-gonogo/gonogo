/**
 * Writes `src/check/rules/imports/private-packages.generated.ts`: the names of
 * the gonogo workspace packages, split by their `"private"` flag. `check`
 * reports the private ones as unreachable for an Uplink. A package the workspace does not hold is never
 * on the list, so a package from another repository under the same scope is
 * judged on what it is rather than where its scope came from.
 *
 *   node scripts/private-packages.mjs [--stdout]
 */
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(HERE, "../../..");
export const OUT = resolve(
  HERE,
  "../src/check/rules/imports/private-packages.generated.ts",
);

const SCOPE = "@ksp-gonogo/";

function manifestsUnder(parent, nested = "") {
  const dir = join(ROOT, parent);
  if (!existsSync(dir)) return [];
  return readdirSync(dir, { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .map((entry) => join(dir, entry.name, nested, "package.json"))
    .filter((path) => existsSync(path));
}

/** The names, without the scope, of every package the workspace globs reach whose `private` flag is `isPrivate`. */
export function workspacePackages(isPrivate) {
  const manifests = [
    ...manifestsUnder("packages"),
    ...manifestsUnder("mod"),
    ...manifestsUnder("mod", "client"),
  ];
  const names = new Set();
  for (const path of manifests) {
    const manifest = JSON.parse(readFileSync(path, "utf8"));
    if (
      (manifest.private === true) === isPrivate &&
      manifest.name?.startsWith(SCOPE)
    ) {
      names.add(manifest.name.slice(SCOPE.length));
    }
  }
  return [...names].sort();
}

const list = (names) => `[\n${names.map((n) => `  "${n}",\n`).join("")}]`;

export function generatedSource() {
  return `// Generated by scripts/private-packages.mjs from the workspace's package manifests. Do not edit.
export const PRIVATE_PACKAGES: readonly string[] = ${list(workspacePackages(true))};
export const WORKSPACE_PUBLISHED_PACKAGES: readonly string[] = ${list(workspacePackages(false))};
`;
}

if (
  process.argv[1] &&
  resolve(process.argv[1]) === fileURLToPath(import.meta.url)
) {
  if (process.argv.includes("--stdout"))
    process.stdout.write(generatedSource());
  else writeFileSync(OUT, generatedSource());
}
