import {
  existsSync,
  mkdirSync,
  mkdtempSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { afterEach, describe, expect, it, vi } from "vitest";
import { run } from "../cli";
import { check } from "./command";
import { runCheck } from "./run";
import type { ClientScan, FixableFinding, Rule } from "./types";

const scratch: string[] = [];
afterEach(() => {
  vi.restoreAllMocks();
  for (const dir of scratch.splice(0))
    rmSync(dir, { recursive: true, force: true });
});

const HOOKS = `
export declare function useTelemetry(topic: string): unknown;
export declare function useStream(topic: string): unknown;
export declare function useCommand(command: string): unknown;
export declare function registerComponent(def: object): void;
`;

const WIDGET = (
  read: string,
) => `import { registerComponent, useTelemetry, useStream, useCommand } from "./hooks";
function Twr(props: { topic: string }) {
  useTelemetry("vessel.flight");
  useStream("vessel.identity");
  useCommand("vessel.control.setSas");
  ${read}
  return null;
}
registerComponent({ id: "twr", channels: ["vessel.flight"], component: Twr });
`;

const EXPECTED = `// twr.declarations.g.ts (generated by uplink-tools check --fix, do not edit)
export const optionalChannels = ["vessel.identity"] as const;
export const optionalChannelFamilies = [] as const;
export const commands = ["vessel.control.setSas"] as const;
`;

/** A client on disk: a tsconfig and a widget, with the generated file present or not. */
function client(options: { read?: string; generated?: string | null } = {}) {
  const dir = mkdtempSync(join(tmpdir(), "gonogo-check-"));
  scratch.push(dir);
  mkdirSync(join(dir, "src"));
  writeFileSync(
    join(dir, "tsconfig.json"),
    JSON.stringify({
      compilerOptions: {
        target: "es2022",
        module: "esnext",
        moduleResolution: "bundler",
        jsx: "react-jsx",
        strict: true,
        skipLibCheck: true,
        types: [],
        noEmit: true,
      },
      include: ["src"],
    }),
  );
  writeFileSync(join(dir, "src/hooks.ts"), HOOKS);
  writeFileSync(join(dir, "src/twr.tsx"), WIDGET(options.read ?? ""));
  if (options.generated !== null) {
    writeFileSync(
      join(dir, "src/twr.declarations.g.ts"),
      options.generated ?? EXPECTED,
    );
  }
  return dir;
}

async function runIn(
  dir: string,
  args: string[] = [],
  env: NodeJS.ProcessEnv = {},
) {
  const log = vi.spyOn(console, "log").mockImplementation(() => {});
  const error = vi.spyOn(console, "error").mockImplementation(() => {});
  const code = await check(["--client", dir, ...args], dir, env);
  const out = log.mock.calls.map((c) => String(c[0])).join("\n");
  const err = error.mock.calls.map((c) => String(c[0])).join("\n");
  return { code, out, err };
}

describe("exit codes", () => {
  it("is 0 when the tree is current", async () => {
    const { code, out } = await runIn(client(), ["--only", "declarations"]);
    expect(code).toBe(0);
    expect(out).toContain("nothing found");
  });

  it("is 1 when a generated file is missing, naming the file and the fix", async () => {
    const dir = client({ generated: null });
    const { code, out } = await runIn(dir, ["--json"]);
    expect(code).toBe(1);
    const [finding] = JSON.parse(out);
    expect(finding).toMatchObject({
      rule: "declarations/stale",
      severity: "error",
      fixable: true,
      fix: "uplink-tools check --fix --only declarations",
    });
    expect(Object.keys(finding).sort()).toEqual(
      ["file", "fix", "fixable", "line", "message", "rule", "severity"].sort(),
    );
  });

  it("is 1 when the generated file no longer matches what the widget reads", async () => {
    const dir = client({
      generated: EXPECTED.replace("vessel.identity", "gone"),
    });
    const { code, out } = await runIn(dir);
    expect(code).toBe(1);
    expect(out).toContain("error declarations/stale");
  });

  it("fails on a planted unresolved read, so a scan that sees nothing cannot pass", async () => {
    const dir = client({ read: "useStream(props.topic);" });
    const { code, out } = await runIn(dir);
    expect(code).toBe(1);
    expect(out).toContain("error declarations/unresolved");
    expect(out).toContain("gonogo:reads");
  });

  it("is 0 once a directive names the planted read and the generated file declares it", async () => {
    const dir = client({
      read: "// gonogo:reads fleet.<vessel>.contact\n  useStream(props.topic);",
      generated: EXPECTED.replace(
        "optionalChannelFamilies = []",
        'optionalChannelFamilies = ["fleet.<vessel>.contact"]',
      ),
    });
    const { code } = await runIn(dir);
    expect(code).toBe(0);
  });

  it("is 2 when it cannot run: no client, an unknown group, a bad number", async () => {
    const empty = mkdtempSync(join(tmpdir(), "gonogo-check-"));
    scratch.push(empty);
    expect((await runIn(empty)).code).toBe(2);
    const dir = client();
    const unknown = await runIn(dir, ["--only", "nonsense"]);
    expect(unknown.code).toBe(2);
    expect(unknown.err).toContain("is not a group");
    expect((await runIn(dir, ["--max-warnings", "lots"])).code).toBe(2);
  });

  it("reports a group with no rule as not checked rather than green", async () => {
    const { code, out } = await runIn(client(), ["--only", "page"]);
    expect(code).toBe(0);
    expect(out).toContain("Not checked");
    expect(out).toContain("page");
  });

  it("leaves a skipped group out", async () => {
    const dir = client({ generated: null });
    expect((await runIn(dir, ["--skip", "declarations"])).code).toBe(0);
  });
});

describe("--fix", () => {
  it("is refused under CI and writes nothing", async () => {
    const dir = client({ generated: null });
    const { code, err } = await runIn(dir, ["--fix"], { CI: "true" });
    expect(code).toBe(2);
    expect(err).toContain("--fix is refused when CI is set");
    expect(existsSync(join(dir, "src/twr.declarations.g.ts"))).toBe(false);
  });

  it("writes the generated file, re-verifies, and a plain run then passes", async () => {
    const dir = client({ generated: null });
    const fixed = await runIn(dir, ["--fix"], {});
    expect(fixed.code).toBe(0);
    expect(fixed.out).toContain("1 fixed");
    expect(readFileSync(join(dir, "src/twr.declarations.g.ts"), "utf8")).toBe(
      EXPECTED,
    );
    expect((await runIn(dir, [], { CI: "true" })).code).toBe(0);
  });

  it("cannot heal an unresolved read and still exits 1", async () => {
    const dir = client({ read: "useStream(props.topic);", generated: null });
    const { code, out } = await runIn(dir, ["--fix"]);
    expect(code).toBe(1);
    expect(out).toContain("declarations/unresolved");
  });
});

describe("runCheck", () => {
  const emptyScan: ClientScan = { widgets: [], directives: [], typeErrors: 0 };
  const finding = (severity: "error" | "warning"): FixableFinding => ({
    rule: "g/r",
    severity,
    file: "f",
    line: 1,
    message: "m",
    fixable: false,
    fix: "x",
  });
  const rule = (severity: "error" | "warning"): Rule => ({
    id: "g/r",
    group: "g",
    check: () => [finding(severity)],
  });
  const base = {
    groups: ["g"],
    clientDir: "/c",
    scan: () => emptyScan,
    env: {},
  };

  it("fails on an error, passes a warning, and fails it under --max-warnings 0", () => {
    expect(runCheck({ ...base, rules: [rule("error")] }).exitCode).toBe(1);
    expect(runCheck({ ...base, rules: [rule("warning")] }).exitCode).toBe(0);
    expect(
      runCheck({ ...base, rules: [rule("warning")], maxWarnings: 0 }).exitCode,
    ).toBe(1);
  });

  it("applies a fixable finding once and re-verifies", () => {
    let healed = false;
    const fixable: Rule = {
      id: "g/f",
      group: "g",
      check: () =>
        healed
          ? []
          : [
              {
                ...finding("error"),
                fixable: true,
                apply: () => (healed = true),
              },
            ],
    };
    const result = runCheck({ ...base, rules: [fixable], fix: true });
    expect(result).toMatchObject({ exitCode: 0, fixed: 1, findings: [] });
  });

  it.each(["true", "1", "yes"])("refuses --fix when CI=%s", (value) => {
    expect(() =>
      runCheck({ ...base, rules: [], fix: true, env: { CI: value } }),
    ).toThrow(/refused when CI is set/);
  });

  it.each(["", "0", "false"])("allows --fix when CI=%j", (value) => {
    expect(
      runCheck({ ...base, rules: [], fix: true, env: { CI: value } }).exitCode,
    ).toBe(0);
  });
});

describe("the command line", () => {
  it("answers --help and is listed", async () => {
    const log = vi.spyOn(console, "log").mockImplementation(() => {});
    expect(await run(["check", "--help"])).toBe(0);
    expect(String(log.mock.calls[0][0])).toContain("uplink-tools check");
    log.mockClear();
    await run(["--help"]);
    expect(String(log.mock.calls[0][0])).toMatch(/\n {2}check /);
  });
});
